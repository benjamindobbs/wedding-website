let currentStoryIndex = 0;
let isStoryAnimating  = false;

document.addEventListener('DOMContentLoaded', () => {
    const imageWraps = document.querySelectorAll('.story-image-wrap');
    imageWraps.forEach((wrap, index) => {
        wrap.style.cursor = 'pointer';
        wrap.addEventListener('click', () => showStoryEntry(index, null));
    });

    // Touch swipe on the detail view
    const detailView = document.getElementById('story-detail-view');
    let swipeStartX = 0;
    let swipeStartY = 0;
    detailView.addEventListener('touchstart', (e) => {
        swipeStartX = e.touches[0].clientX;
        swipeStartY = e.touches[0].clientY;
    }, { passive: true });
    detailView.addEventListener('touchend', (e) => {
        const dx = e.changedTouches[0].clientX - swipeStartX;
        const dy = e.changedTouches[0].clientY - swipeStartY;
        if (Math.abs(dx) >= Math.abs(dy)) {
            if (Math.abs(dx) < 50) return;
            if (dx < 0) nextStoryEntry();
            else prevStoryEntry();
        }
    }, { passive: true });
});

function showStoryEntry(index, direction) {
    currentStoryIndex = index;
    const entry      = storyEntries[index];
    const listView   = document.getElementById('story-list-view');
    const detailView = document.getElementById('story-detail-view');
    const card       = detailView.querySelector('.detail-card');

    if (!direction) {
        _updateStoryContent(entry);
        listView.style.display   = 'none';
        detailView.style.display = 'block';
        window.scrollTo(0, 0);
        return;
    }

    if (isStoryAnimating) return;
    isStoryAnimating = true;

    const exitClass  = direction === 'next' ? 'exit-left'   : 'exit-right';
    const enterClass = direction === 'next' ? 'enter-right' : 'enter-left';

    card.classList.add(exitClass);

    card.addEventListener('animationend', function onExit() {
        card.removeEventListener('animationend', onExit);
        card.classList.remove(exitClass);

        _updateStoryContent(entry);

        void card.offsetWidth;
        card.classList.add(enterClass);

        card.addEventListener('animationend', function onEnter() {
            card.removeEventListener('animationend', onEnter);
            card.classList.remove(enterClass);
            isStoryAnimating = false;
        }, { once: true });
    }, { once: true });
}

function _updateStoryContent(entry) {
    document.getElementById('story-detail-img').src          = entry.image;
    document.getElementById('story-detail-img').alt          = entry.caption;
    document.getElementById('story-detail-subtitle').innerText = entry.date;
    document.getElementById('story-detail-name').innerText   = entry.caption;
    document.getElementById('story-detail-flavor').innerHTML = entry.text;

    const img2       = document.getElementById('story-detail-img2');
    const photoWrap  = document.querySelector('#story-detail-view .detail-photo');
    if (entry.extraImage) {
        img2.src             = entry.extraImage;
        img2.alt             = entry.caption;
        img2.style.display   = 'block';
        photoWrap.classList.add('has-extra-image');
    } else {
        img2.style.display   = 'none';
        photoWrap.classList.remove('has-extra-image');
    }
}

function nextStoryEntry() {
    const next = (currentStoryIndex + 1) % storyEntries.length;
    showStoryEntry(next, 'next');
}

function prevStoryEntry() {
    const prev = (currentStoryIndex - 1 + storyEntries.length) % storyEntries.length;
    showStoryEntry(prev, 'prev');
}

function closeStory() {
    const listView   = document.getElementById('story-list-view');
    const detailView = document.getElementById('story-detail-view');
    detailView.style.display = 'none';
    listView.style.display   = 'block';
    window.scrollTo(0, 0);
}
